// Label 标签组件
type Label struct {
	BaseComponent
	text        string
	font        *Font
	textColor   graphics.Color
	background  graphics.Color
	align       TextAlign
	valign      VerticalAlign
	isSecondary bool
	isBrand     bool
	customColor bool
	ellipsis    bool
	clickable   bool
	onClick     func()
}

// TextAlign 文本水平对齐
type TextAlign int

const (
	AlignLeft TextAlign = iota
	AlignCenter
	AlignRight
)

// VerticalAlign 文本垂直对齐
type VerticalAlign int

const (
	AlignTop VerticalAlign = iota
	AlignMiddle
	AlignBottom
)

// NewLabel 创建标签（默认主正文文本，自动跟随主题色彩）
func NewLabel(text string) *Label {
	l := &Label{
		BaseComponent: NewBaseComponent(),
		text:          text,
		font:          DefaultFont,
		background:    graphics.ColorTransparent,
		align:         AlignLeft,
		valign:        AlignMiddle,
	}
	l.ApplyTheme(theme.Current())
	return l
}

// NewSecondaryLabel 创建次级说明文本标签（自动跟随主题 TextSecondary）
func NewSecondaryLabel(text string) *Label {
	l := NewLabel(text)
	l.SetSecondary(true)
	return l
}

// NewBrandLabel 创建品牌强调标题标签（自动跟随主题 Primary 品牌强调色）
func NewBrandLabel(text string) *Label {
	l := NewLabel(text)
	l.SetBrand(true)
	return l
}

// SetSecondary 设置是否为次要说明文本
func (l *Label) SetSecondary(secondary bool) {
	l.isSecondary = secondary
	if secondary {
		l.isBrand = false
	}
	l.customColor = false
	l.ApplyTheme(theme.Current())
}

// SetBrand 设置是否为品牌强调色标题文本
func (l *Label) SetBrand(brand bool) {
	l.isBrand = brand
	if brand {
		l.isSecondary = false
	}
	l.customColor = false
	l.ApplyTheme(theme.Current())
}

// ApplyTheme 应用主题样式
func (l *Label) ApplyTheme(t *theme.Theme) {
	if t == nil || l.customColor {
		return
	}
	if l.isBrand {
		l.textColor = t.Primary
	} else if l.isSecondary {
		l.textColor = t.TextSecondary
	} else {
		l.textColor = t.TextPrimary
	}
}

// Render 渲染标签
func (l *Label) Render(canvas *render.Canvas) {
	if !l.visible {
		return
	}

	bounds := l.bounds

	// 绘制背景
	if l.background != graphics.ColorTransparent {
		canvas.FillRect(bounds.X, bounds.Y, bounds.Width, bounds.Height, l.background)
	}

	// 绘制文本（裁剪到标签边界，避免长路径/长状态文本覆盖相邻控件）
	if l.text != "" {
		canvas.PushClip(bounds)
		l.renderText(canvas, bounds)
		canvas.PopClip()
	}
}

// renderText 渲染文本
func (l *Label) renderText(canvas *render.Canvas, bounds graphics.Rect) {
	text := l.text
	if l.ellipsis {
		text = l.ellipsizedText(canvas, text, bounds.Width-8)
		if text == "" {
			return
		}
	}
	textWidth, textHeight := canvas.MeasureText(text, l.font)

	// 计算水平位置
	var x int32
	switch l.align {
	case AlignLeft:
		x = bounds.X + 4
	case AlignCenter:
		x = bounds.X + (bounds.Width-textWidth)/2
	case AlignRight:
		x = bounds.X + bounds.Width - textWidth - 4
	}

	// 计算垂直位置
	var y int32
	switch l.valign {
	case AlignTop:
		y = bounds.Y + 2
	case AlignMiddle:
		y = bounds.Y + (bounds.Height-textHeight)/2
	case AlignBottom:
		y = bounds.Y + bounds.Height - textHeight - 2
	}

	canvas.DrawText(text, x, y, l.font, l.textColor)
}

// ellipsizedText 在最大宽度内按 rune 截断并追加省略号。
func (l *Label) ellipsizedText(canvas *render.Canvas, text string, maxWidth int32) string {
	if maxWidth <= 0 {
		return ""
	}
	if width, _ := canvas.MeasureText(text, l.font); width <= maxWidth {
		return text
	}
	const ellipsis = "…"
	ellipsisWidth, _ := canvas.MeasureText(ellipsis, l.font)
	if ellipsisWidth > maxWidth {
		return ""
	}

	fm := render.GetFontManager()
	face := fm.GetFace(l.font)
	if face == nil {
		return ellipsis
	}
	runes := []rune(text)
	acc := int32(0)
	for i, r := range runes {
		width := fm.RuneWidthFace(face, r)
		if acc+width+ellipsisWidth > maxWidth {
			return string(runes[:i]) + ellipsis
		}
		acc += width
	}
	return text
}

// OnEvent 处理点击事件
func (l *Label) OnEvent(evt event.Event) bool {
	if !l.visible || !l.enabled {
		return false
	}
	data, ok := evt.Data.(event.MouseData)
	if !ok {
		return false
	}
	inside := IsInBounds(data.X, data.Y, l.bounds)
	switch evt.Type {
	case event.EventMouseDown:
		if !l.clickable || data.Button != event.MouseButtonLeft || !inside {
			return false
		}
		if l.onClick != nil {
			l.onClick()
		}
		return true
	case event.EventMouseUp:
		return l.clickable && inside
	}
	return false
}

// SetText 设置文本
func (l *Label) SetText(text string) {
	l.text = text
}

// GetText 获取文本
func (l *Label) GetText() string {
	return l.text
}

// SetFont 设置字体
func (l *Label) SetFont(font *Font) {
	l.font = font
}

// GetFont 获取字体
func (l *Label) GetFont() *Font {
	return l.font
}

// SetTextColor 设置自定义文本颜色（设置后不再被自动主题覆盖）
func (l *Label) SetTextColor(color graphics.Color) {
	l.customColor = true
	l.textColor = color
}

// SetBackground 设置背景颜色
func (l *Label) SetBackground(color graphics.Color) {
	l.background = color
}

// SetAlign 设置水平对齐
func (l *Label) SetAlign(align TextAlign) {
	l.align = align
}

// SetEllipsis 设置超出边界时是否以省略号截断。
func (l *Label) SetEllipsis(enabled bool) {
	l.ellipsis = enabled
}

// SetOnClick 设置点击回调；设置后标签显示手型光标并消费点击事件。
func (l *Label) SetOnClick(fn func()) {
	l.onClick = fn
	l.clickable = fn != nil
}

// GetCursor 返回鼠标光标；可点击标签使用手型光标。
func (l *Label) GetCursor() int {
	if l.clickable {
		return 32649
	}
	return 0
}

// SetVAlign 设置垂直对齐
func (l *Label) SetVAlign(valign VerticalAlign) {
	l.valign = valign
}

